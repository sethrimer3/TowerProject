import {readFileSync,writeFileSync} from 'node:fs';
import {decodePng,encodePng} from './ui-atlas-png.mjs';
import {createHash} from 'node:crypto';
const output='public/assets/atlases';
const ui=JSON.parse(readFileSync(output+'/ui.json'));
const source=readFileSync('src/sprites/assets.ts','utf8');
const paths=JSON.parse(source.slice(source.indexOf('['),source.lastIndexOf(']')+1));
const entries=paths.filter(path=>!ui.regions[path]).map(path=>{const p=decodePng(readFileSync('public/'+path));return {path,width:p.width,height:p.height}});
entries.sort((a,b)=>b.height-a.height||b.width-a.width||a.path.localeCompare(b.path));
const width=2048,padding=2;let x=padding,y=padding,rowHeight=0;
for(const e of entries){if(e.width+padding*2>width)throw Error(`Sprite exceeds atlas width: ${e.path}`);if(x+e.width+padding>width){x=padding;y+=rowHeight+padding*2;rowHeight=0;}e.x=x;e.y=y;x+=e.width+padding*2;rowHeight=Math.max(rowHeight,e.height);}
const height=2**Math.ceil(Math.log2(y+rowHeight+padding));
const pixels=Buffer.alloc(width*height*4);
for(const e of entries){const input=decodePng(readFileSync(`public/${e.path}`));
 if(input.width!==e.width||input.height!==e.height)throw Error(`Manifest dimensions differ: ${e.path}`);
 for(let row=0;row<e.height;row++)input.pixels.copy(pixels,((e.y+row)*width+e.x)*4,row*e.width*4,(row+1)*e.width*4);
}
const png=encodePng(width,height,pixels);
writeFileSync(output+'/world.png',png);
const revision=createHash('sha256').update(png).digest('hex').slice(0,16);
const regions=Object.fromEntries([...entries].sort((a,b)=>a.path.localeCompare(b.path)).map(({path,...r})=>[path,r]));
const manifest={image:'assets/atlases/world.png',revision,width,height,padding,regions,cssVariables:{}};
writeFileSync(output+'/world.json',JSON.stringify(manifest,null,2)+'\n');
writeFileSync('src/sprites/world-atlas-data.ts','// Generated by tools/build-world-atlas.mjs.\nexport const WORLD_ATLAS = '+JSON.stringify(manifest,null,2)+' as const;\n');
console.log(`Packed ${entries.length} remaining sprites into ${width} × ${height}.`);
