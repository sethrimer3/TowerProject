import {readFileSync,writeFileSync,readdirSync,mkdirSync} from 'node:fs';
import {decodePng,encodePng} from './ui-atlas-png.mjs';
import postcss from 'postcss';
import {createHash} from 'node:crypto';
const output='public/assets/atlases';mkdirSync(output,{recursive:true});
const style=JSON.parse(readFileSync('public/assets/style/manifest.json')).assets;
const entries=[];
for(const [id,a] of Object.entries(style)){
 if(/^(forest-|dungeon-|ambient-|lake-|blacksmith-|hero-|square-door-|env-|water-|moss-|vine-|flower-|glowing-|torch-animation|terrain|tower-[123]-|tower-floor)/.test(id)||a.width>96||a.height>96)continue;
 entries.push({path:`assets/style/${a.file}`,width:a.width,height:a.height});
}
for(const name of readdirSync('public/assets/ui/frames').filter(n=>n.endsWith('.png'))){const b=readFileSync(`public/assets/ui/frames/${name}`);entries.push({path:`assets/ui/frames/${name}`,width:b.readUInt32BE(16),height:b.readUInt32BE(20)});}
entries.sort((a,b)=>b.height-a.height||b.width-a.width||a.path.localeCompare(b.path));
const width=1024,padding=2;let x=padding,y=padding,rowHeight=0;
for(const e of entries){if(x+e.width+padding>width){x=padding;y+=rowHeight+padding*2;rowHeight=0;}e.x=x;e.y=y;x+=e.width+padding*2;rowHeight=Math.max(rowHeight,e.height);}
const height=2**Math.ceil(Math.log2(y+rowHeight+padding));
const pixels=Buffer.alloc(width*height*4);
for(const e of entries){const input=decodePng(readFileSync(`public/${e.path}`));
 if(input.width!==e.width||input.height!==e.height)throw Error(`Manifest dimensions differ: ${e.path}`);
 for(let row=0;row<e.height;row++)input.pixels.copy(pixels,((e.y+row)*width+e.x)*4,row*e.width*4,(row+1)*e.width*4);
}
const png=encodePng(width,height,pixels);
writeFileSync(output+'/ui.png',png);
const revision=createHash('sha256').update(png).digest('hex').slice(0,16);
const regions=Object.fromEntries([...entries].sort((a,b)=>a.path.localeCompare(b.path)).map(({path,...r})=>[path,r]));
const vars={};const overrides=postcss.root();
const prefix=s=>s.replace(/^html(?=[\s.#:[>]|$)/,'html.experimental-atlas').replace(/^:root/,'html.experimental-atlas');
for(const name of readdirSync('src').filter(n=>n.endsWith('.css'))){const root=postcss.parse(readFileSync(`src/${name}`,'utf8'));
 root.walkRules(rule=>{
  const declarations=[];
  for(const d of rule.nodes??[]){if(d.type!=='decl')continue;let changed=false;
   const value=d.value.replace(/url\(["']?([^"')]+)["']?\)/g,(whole,url)=>{const path=url.replace(/^\.\.\/public\//,'');if(!regions[path])return whole;changed=true;vars[path]??=`--atlas-${Object.keys(vars).length}`;return `var(${vars[path]}, none)`});
   if(changed)declarations.push(d.clone({value}));
  }
  if(!declarations.length)return;
  const r=postcss.rule({selector:rule.selectors.map(s=>/^html(?=[\s.#:[>]|$)|^:root/.test(s.trim())?prefix(s.trim()):`html.experimental-atlas ${s.trim()}`).join(',\n')});r.append(declarations);
  let wrapped=r,parent=rule.parent;while(parent&&parent.type!=='root'){if(parent.type==='atrule'){const a=parent.clone({nodes:[]});a.append(wrapped);wrapped=a;}parent=parent.parent;}overrides.append(wrapped);
 });
}
const manifest={image:'assets/atlases/ui.png',revision,width,height,padding,regions,cssVariables:vars};
writeFileSync(output+'/ui.json',JSON.stringify(manifest,null,2)+'\n');
writeFileSync('src/sprites/ui-atlas-data.ts','// Generated by tools/build-ui-atlas.mjs.\nexport const UI_ATLAS = '+JSON.stringify(manifest,null,2)+' as const;\n');
writeFileSync('src/sprites/ui-atlas.css','/* Generated atlas-only CSS image sources; original files stay intact. */\n'+overrides.toString()+'\n');
console.log(`Packed ${entries.length} UI images into ${width} × ${height}; ${Object.keys(vars).length} CSS image slices.`);
