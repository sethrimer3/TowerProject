for alias, original in {"−": "-", "–": "-", "—": "-", "‘": "'", "’": "'", "“": '"', "”": '"', "·": "•", "✕": "×", "✦": "★", "✧": "★", "✔": "✓"}.items():
    ROWS[alias] = ROWS[original]

def glyph(rows):
    pen = TTGlyphPen(None)
    for y, row in enumerate(rows):
        start = None
        for x, cell in enumerate(row + "."):
            if cell == "#" and start is None:
                start = x
            elif cell != "#" and start is not None:
                left, bottom, right = start * 100, (6 - y) * 100, x * 100
                pen.moveTo((left, bottom)); pen.lineTo((left, bottom + 100))
                pen.lineTo((right, bottom + 100)); pen.lineTo((right, bottom)); pen.closePath()
                start = None
    return pen.glyph()

def build():
    rows = {char: value.split("/") for char, value in ROWS.items()}
    assert set(map(chr, range(33, 127))) <= rows.keys(), "complete printable ASCII"
    for char, lines in rows.items():
        assert len({len(line) for line in lines}) == 1, char
    names = {char: f"uni{ord(char):04X}" for char in sorted(rows)}
    order = [".notdef", "space", *names.values()]
    glyphs = {".notdef": glyph(["#####", "#...#", "#.#.#", "#...#", "#####"]), "space": glyph([])}
    glyphs.update({names[char]: glyph(lines) for char, lines in rows.items()})
    metrics = {".notdef": (600, 0), "space": (300, 0)}
    metrics.update({names[char]: ((len(lines[0]) + 1) * 100, 0) for char, lines in rows.items()})
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order); fb.setupCharacterMap({32: "space", 160: "space", **{ord(c): n for c, n in names.items()}})
    fb.setupGlyf(glyphs); fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({"familyName": "Tower Pixel", "styleName": "Regular", "uniqueFontIdentifier": "TowerPixel-1.0", "fullName": "Tower Pixel", "psName": "TowerPixel-Regular", "version": "Version 1.0"})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=0, usWinAscent=800, usWinDescent=200, sxHeight=500, sCapHeight=700)
    fb.setupPost(); fb.setupMaxp()
    # Stable timestamps make regeneration byte-identical.
    fb.font["head"].created = fb.font["head"].modified = 2082844800
    fb.font.recalcTimestamp = False
    fb.font.flavor = "woff2"
    dest = Path(__file__).resolve().parents[1] / "assets/fonts/TowerPixel/TowerPixel-Regular.woff2"
    fb.save(dest)
    print(f"Built {dest.name}: {len(names) + 2} glyphs, {dest.stat().st_size} bytes")

if __name__ == "__main__":
    build()
