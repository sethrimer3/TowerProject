import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// Only deployed artwork belongs in the startup barrier; authoring atlases
// and manifests are not image requests. Keep Defend's separate assets intact.
const assets = [];
function scan(dir) {
  for (const item of readdirSync(`public/${dir}`, { withFileTypes: true })) {
    const path = join(dir, item.name).replaceAll("\\", "/");
    if (item.isDirectory()) scan(path);
    else if (/\.(png|svg|webp|jpe?g|gif)$/i.test(item.name)) assets.push(path);
  }
}
for (const dir of ["assets/style", "assets/ui/frames", "assets/themes", "assets/defend"]) scan(dir);
assets.sort();
writeFileSync("src/sprites/assets.ts", `// Generated by tools/build-sprite-manifest.mjs.\nexport const SPRITE_ASSETS = ${JSON.stringify(assets, null, 2)} as const;\n`);
console.log(`Registered ${assets.length} startup images.`);
